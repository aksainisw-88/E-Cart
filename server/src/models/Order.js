const mongoose = require("mongoose");

const orderSchema = new mongoose.Schema(
  {
    orderNumber: { type: String, unique: true, required: true },
    customer: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true },
    store: { type: mongoose.Schema.Types.ObjectId, ref: "StoreLocation" },
    items: [{ product: mongoose.Schema.Types.ObjectId, name: String, price: Number, costPrice: Number, originalPrice: Number, discount: Number, discountAmount: Number, quantity: Number, image: String, returnEligible: Boolean, replaceEligible: Boolean }],
    shipping: { name: String, phone: String, address: String, city: String, pincode: String },
    subtotal: { type: Number, required: true },
    discount: { type: Number, default: 0, min: 0 },
    promoCode: { type: String, trim: true, uppercase: true, default: "" },
    promoDiscount: { type: Number, default: 0, min: 0 },
    delivery: { type: Number, required: true },
    total: { type: Number, required: true },
    paymentMethod: { type: String, enum: ["card", "razorpay", "cod", "phonepe", "paytm", "googlepay"], default: "card" },
    paymentStatus: { type: String, enum: ["Pending", "Paid", "Failed"], default: "Pending" },
    utrNumber: { type: String, trim: true, default: "" },
    paymentNotes: { type: String, trim: true, default: "" },
    razorpayOrderId: { type: String, trim: true, default: "" },
    razorpayPaymentId: { type: String, trim: true, default: "" },
    razorpaySignature: { type: String, trim: true, default: "" },
    paidAt: { type: Date },
    status: { type: String, enum: ["Processing", "Shipped", "Delivered", "Cancelled"], default: "Processing" },
    cancelReason: { type: String, trim: true, maxlength: 500, default: "" },
    cancelledAt: { type: Date },
    returnStatus: { type: String, enum: ["Not requested", "Requested", "Approved", "Rejected", "Completed"], default: "Not requested" },
    returnType: { type: String, enum: ["Return", "Replacement"], default: "Return" },
    returnReason: { type: String, trim: true, maxlength: 500, default: "" },
    returnRequestedAt: { type: Date },
    returnReviewedAt: { type: Date },
    returnCompletedAt: { type: Date },
    returnAdminNote: { type: String, trim: true, maxlength: 500, default: "" },
    refundStatus: { type: String, enum: ["Not refunded", "Processing", "Refunded", "Failed"], default: "Not refunded" },
    refundAmount: { type: Number, min: 0, default: 0 },
    refundMethod: { type: String, enum: ["Razorpay", "Manual", ""], default: "" },
    refundId: { type: String, trim: true, default: "" },
    refundNote: { type: String, trim: true, maxlength: 500, default: "" },
    refundedAt: { type: Date },
  },
  { timestamps: true },
);

module.exports = mongoose.model("Order", orderSchema);